// terminal-launcher.js - open the server log in the user's DEFAULT terminal.
//
// WHY THIS FILE EXISTS
//
// The "Open Terminal Logs" tray item used to run, as a single shell string:
//
//   osascript -e 'tell application "Terminal" to do script "tail -f ..."'
//
// That is wrong in two independent ways, and both of them are invisible.
//
// 1. `do script` CREATES a window but does not RAISE the application.
//    Terminal keeps its place in the window order, so on a busy desktop the
//    window is created behind everything and the user sees nothing happen at
//    all. The tail is genuinely running; it is simply not visible. Clicking
//    the menu item again just starts another one. Two orphaned `tail -f`
//    processes with no window were found on the development machine, which is
//    exactly the signature of this bug. `activate` is the missing word.
//
// 2. It hardcodes Terminal.app. If the user's terminal is iTerm2, Warp,
//    Ghostty or kitty, the log opens in an app they do not use, while the
//    sibling "Open in Browser" item correctly honours their default browser
//    through shell.openExternal.
//
// macOS exposes no "default terminal" setting, but LaunchServices routes
// `.command` / `.tool` documents to a registered handler, and every terminal
// emulator that wants to be scriptable registers for it. So writing a small
// executable `.command` script and handing it to shell.openPath is the
// document-opening equivalent of shell.openExternal: it lands in whichever
// terminal the user actually chose, and it foregrounds the way opening any
// document foregrounds its app.
//
// THREE OUTCOMES, not two. Resolving the handler can succeed, fail, or be
// impossible to determine. "Could not determine a handler" is NOT the same as
// "opened successfully" and NOT the same as "the open failed": it falls back
// to Terminal.app with an explicit `activate` AND reports usedFallback so the
// caller can tell the user that a substitution happened. Silently doing
// something other than what the user asked for is the failure mode this
// module exists to avoid.
//
// Every side-effecting dependency is injected so the whole flow is testable
// without an Electron runtime or a real desktop.

'use strict';

const DEFAULT_SCRIPT_BASENAME = 'open-server-log.command';

/**
 * Quote a string for safe literal use inside a POSIX shell single-quoted
 * word. Single quotes suppress ALL expansion, so spaces, `$`, and backticks
 * are inert. The only character that cannot appear inside a single-quoted
 * word is a single quote, which is emitted by closing the quote, adding an
 * escaped quote, and reopening.
 *
 * Single quoting is deliberate, not incidental: a backtick inside a
 * DOUBLE-quoted shell word is command substitution, which is a live code path
 * hiding inside what looks like inert data.
 *
 * @param {string} value - Raw text to embed in a shell command.
 * @returns {string} The text wrapped in single quotes and fully escaped.
 */
function shellSingleQuote(value) {
  return "'" + String(value).replace(/'/g, "'\\''") + "'";
}

/**
 * Escape a string for embedding inside an AppleScript double-quoted string
 * literal. AppleScript recognises exactly two escapes there, backslash and
 * double quote, so those are the only characters that need rewriting.
 *
 * @param {string} value - Raw text to embed.
 * @returns {string} The text with backslashes and double quotes escaped.
 */
function escapeAppleScriptString(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/**
 * Build the contents of the `.command` script that tails the log.
 *
 * The log path is single-quoted, because it lives under
 * "~/Library/Application Support/..." and always contains spaces.
 *
 * @param {string} logPath - Absolute path of the log file to tail.
 * @returns {string} A complete bash script, newline terminated.
 */
function buildTailCommandScript(logPath) {
  const quoted = shellSingleQuote(logPath);
  return [
    '#!/bin/bash',
    '# Generated by Cloude Code. Overwritten on each use; safe to delete.',
    'clear',
    'echo "Cloude Code server log"',
    'echo ' + quoted,
    'echo',
    'exec tail -f ' + quoted,
    '',
  ].join('\n');
}

/**
 * Build the fallback AppleScript that drives Terminal.app directly.
 *
 * `activate` is issued AFTER `do script` so that the window just created is
 * the one brought forward. Without `activate` the window opens behind
 * everything and the feature reads as broken.
 *
 * There are TWO nested quoting layers here and they must be composed in the
 * right order. The inner layer is a shell command line, the outer layer is an
 * AppleScript string literal holding it. So the path is single-quoted for the
 * SHELL first (which neutralises spaces, `$`, backticks and double quotes),
 * and the resulting shell word is then escaped for AppleScript. Escaping only
 * for AppleScript, as an earlier version did, leaves a path containing a
 * double quote to terminate the shell word and break the tail command.
 *
 * @param {string} logPath - Absolute path of the log file to tail.
 * @returns {string} A complete AppleScript program.
 */
function buildTerminalAppleScript(logPath) {
  const shellWord = shellSingleQuote(logPath);
  const embedded = escapeAppleScriptString('tail -f ' + shellWord);
  return [
    'tell application "Terminal"',
    '  do script "' + embedded + '"',
    '  activate',
    'end tell',
  ].join('\n');
}

/**
 * Ask LaunchServices which application is registered to open a `.command`
 * file, i.e. the user's effective default terminal.
 *
 * Resolution runs through NSWorkspace via the JXA ObjC bridge because
 * Electron exposes no binding for URLForApplicationToOpenURL. The probe file
 * must already exist, since LaunchServices resolves a concrete URL.
 *
 * @param {string} probePath - Path to an existing `.command` file.
 * @param {(handlerPath: string|null) => void} callback - Receives the
 *   absolute path of the handling application bundle, or null when no handler
 *   could be determined. null is a THIRD outcome and callers must not treat
 *   it as either success or failure.
 * @param {{execFile: Function}} deps - Injected child_process.execFile.
 * @returns {void}
 */
function detectDefaultCommandHandler(probePath, callback, deps) {
  const jxa = [
    'ObjC.import("AppKit");',
    'var u = $.NSURL.fileURLWithPath($(' + JSON.stringify(probePath) + '));',
    'var a = $.NSWorkspace.sharedWorkspace.URLForApplicationToOpenURL(u);',
    'a.isNil() ? "" : ObjC.unwrap(a.path);',
  ].join('\n');

  deps.execFile('osascript', ['-l', 'JavaScript', '-e', jxa], (error, stdout) => {
    if (error) return callback(null);
    const resolved = String(stdout || '').trim();
    callback(resolved || null);
  });
}

/**
 * Fallback path: open a Terminal.app window tailing the log and raise it.
 *
 * @param {string} logPath - Absolute path of the log file to tail.
 * @param {(error: Error|null) => void} callback - Receives the osascript
 *   error, or null on success.
 * @param {{execFile: Function}} deps - Injected child_process.execFile.
 * @returns {void}
 */
function openTerminalTail(logPath, callback, deps) {
  const script = buildTerminalAppleScript(logPath);
  deps.execFile('osascript', ['-e', script], (error) => {
    callback(error || null);
  });
}

/**
 * Open the server log in the user's default terminal, tailing it live.
 *
 * Order of attempts:
 *   1. Write an executable `.command` script and hand it to LaunchServices
 *      via shell.openPath, which routes to the user's real default terminal.
 *   2. On any failure, or when no handler can be resolved, drive Terminal.app
 *      over AppleScript WITH `activate`, and report usedFallback: true.
 *
 * The `.command` file is written to a single STABLE path and overwritten on
 * every use, so repeated clicks cannot accumulate one temp file per click.
 *
 * @param {string} logPath - Absolute path of the log file to tail.
 * @param {string} scriptPath - Stable absolute path of the `.command` file to
 *   write and reuse.
 * @param {(result: {opened: boolean, handlerPath: (string|null),
 *   usedFallback: boolean, error: (Error|string|null)}) => void} callback -
 *   Reports which route was taken. `opened: false` means neither worked.
 * @param {{fs: object, shell: object, execFile: Function}} deps - Injected
 *   node fs, Electron shell, and child_process.execFile.
 * @returns {void}
 */
function openServerLogInDefaultTerminal(logPath, scriptPath, callback, deps) {
  const runFallback = (reason) => {
    openTerminalTail(
      logPath,
      (fallbackError) => {
        callback({
          opened: !fallbackError,
          handlerPath: null,
          usedFallback: true,
          error: fallbackError || reason || null,
        });
      },
      deps
    );
  };

  try {
    deps.fs.writeFileSync(scriptPath, buildTailCommandScript(logPath), {
      mode: 0o755,
    });
    deps.fs.chmodSync(scriptPath, 0o755);
  } catch (writeError) {
    return runFallback(writeError);
  }

  detectDefaultCommandHandler(
    scriptPath,
    (handlerPath) => {
      if (!handlerPath) return runFallback('no .command handler registered');

      Promise.resolve(deps.shell.openPath(scriptPath))
        .then((openError) => {
          if (openError) return runFallback(openError);
          callback({
            opened: true,
            handlerPath,
            usedFallback: false,
            error: null,
          });
        })
        .catch((thrown) => runFallback(thrown));
    },
    deps
  );
}

module.exports = {
  DEFAULT_SCRIPT_BASENAME,
  shellSingleQuote,
  escapeAppleScriptString,
  buildTailCommandScript,
  buildTerminalAppleScript,
  detectDefaultCommandHandler,
  openTerminalTail,
  openServerLogInDefaultTerminal,
};

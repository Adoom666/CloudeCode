    ALL_FIDELITY_OUTCOMES,
    ALL_ITEM_STATUSES,
    ALL_REAP_VERDICTS,
    ALL_SEVERITIES,
    AUTO_RESOLVABLE_CODES,
    BY_CODE,
    Candidate,
    DISPOSABILITY_HUMAN_DECISION,
    DisposabilitySignal,
    FIDELITY_FAILED,
    FIDELITY_UNVERIFIABLE,
    FIDELITY_VERIFIED,
    GATE_CONDITIONS,
    GATE_DANGLING_PARENT,
    GATE_TOOL_CALL_WITHOUT_RESULT,
    GateCondition,
    GateDecision,
    GatedItem,
    KNOWN_RECORD_TYPES,
    RECORD_TYPES_WITHOUT_TIMESTAMPS,
    REAP_BLOCKED_GATED,
    REAP_BLOCKED_NO_SIGNAL,
    REAP_ELIGIBLE,
    SEVERITY_ADVISORY,
    SEVERITY_STOP,
    STATUS_AUTO_RESOLVED,

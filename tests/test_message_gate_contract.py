"""The message gate contract: registry totality, fidelity's three
outcomes, decision application, and the reaper interlock.

The properties pinned here are the ones that make the contract worth
having, same rationale as test_hook_contract.py: a condition that can be
added to the vocabulary without a recorded severity/description, or a
reaper that can be fooled into eligibility by a gated item, would look
exactly like a working gate right up until it was not.
"""

